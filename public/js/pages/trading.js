import { get, post } from '../api.js';
import { $, el, money, price, pct, clock, duration, toast, openModal, resultBadge, badge } from '../ui.js';
import { store, subscribe, wallet, loadMarkets, setMarket, setWallets, loadConfig } from '../state.js';
import { socket, onSocketMessage } from '../app.js';
import { createChart } from '../chart.js';
import { navigate } from '../router.js';

const PRESETS = [5, 10, 15, 30, 60, 300, 900, 1800, 3600, 7200, 14400, 28800];
const presetLabel = (s) => (s < 60 ? `${s}s` : s < 3600 ? `${s / 60}m` : `${s / 3600}h`);

export async function tradingPage({ outlet }) {
  if (!store.config) await loadConfig();
  const config = store.config;
  const markets = await loadMarkets();
  if (!markets.length) {
    outlet.append(el('div', { class: 'panel center' }, 'No active markets. Ask an admin to open one.'));
    return;
  }
  let market = markets.find((m) => m.symbol === store.activeMarket) ?? markets[0];
  store.activeMarket = market.symbol;

  const chartApi = { current: null };
  let timeframe = localStorage.getItem('st.tf') || '1m';
  if (!config.timeframes.includes(timeframe)) timeframe = '1m';
  let chartType = localStorage.getItem('st.chartType') || 'candle';
  let amount = Number(localStorage.getItem('st.amount') || 10);
  let currency = store.user ? store.displayCurrency : 'USD';
  let durationSec = Number(localStorage.getItem('st.duration') || 60);
  let direction = null;
  let openTrades = [];
  let history = [];
  let marketTicker = { price: null, change24h: null, change24hPercent: null, high24h: null, low24h: null };
  let serverOffset = 0;

  /** decimals of the market currently shown (single source of truth: server) */
  const dps = () => market?.priceDecimals ?? 2;

  // ------------------------------------------------------------------ DOM
  const marketList = el('div', { class: 'market-list' });
  const tickerPanel = el('div', { class: 'ticker-panel' });
  const chartCanvas = el('canvas', { class: 'chart-canvas', id: 'chartCanvas' });
  const chartLegend = el('div', { class: 'chart-legend' });
  const tfBar = el('div', { class: 'tf-bar' });
  const typeBar = el('div', { class: 'type-bar' });
  const overlay = el('div', { class: 'chart-overlay' }, el('span', { class: 'badge sim' }, 'SIMULASI'), el('span', { class: 'muted' }, 'Server-simulated price feed'));
  const openList = el('div', { class: 'trade-list' });
  const historyList = el('div', { class: 'trade-list' });
  const tabs = el('div', { class: 'tabs' });
  let activeTab = 'open';

  const amountInput = el('input', { class: 'amount-input', type: 'number', min: '0', step: 'any', value: String(amount), inputmode: 'decimal' });
  const quickRow = el('div', { class: 'quick-row' });
  const currencySelect = el(
    'select',
    { class: 'currency-select' },
    ...(config.currencies ?? ['USD', 'IDR', 'USDT']).map((c) => el('option', { value: c, ...(c === currency ? { selected: '' } : {}) }, c)),
  );
  const durationGrid = el('div', { class: 'duration-grid' });
  const durationCustom = el('input', {
    class: 'duration-custom',
    type: 'number',
    min: '5',
    max: '28800',
    step: '1',
    value: String(durationSec),
    'aria-label': 'Custom duration in seconds',
  });
  const previewBox = el('div', { class: 'preview-box' });
  const limitsHint = el('p', { class: 'hint small' });
  const balanceHint = el('div', { class: 'balance-line' });
  const buyBtn = el('button', { class: 'trade-btn buy', type: 'button' }, el('span', {}, '▲ BUY / UP'), el('small', {}, 'price rises'));
  const sellBtn = el('button', { class: 'trade-btn sell', type: 'button' }, el('span', {}, '▼ SELL / DOWN'), el('small', {}, 'price falls'));
  const previewBtn = el('button', { class: 'btn ghost block small', type: 'button' }, 'Preview payout & profit');

  const layout = el(
    'div',
    { class: 'trade-layout' },
    el(
      'aside',
      { class: 'panel ml-panel' },
      el('div', { class: 'panel-head' }, el('h2', {}, 'Markets'), badge('SIMULASI', 'sim')),
      marketList,
      el('div', { class: 'panel-foot muted small' }, 'Prices are generated by the server. Historical candles are simulated too.'),
    ),
    el(
      'section',
      { class: 'chart-col' },
      el('div', { class: 'panel chart-panel' }, tickerPanel, tfBar, el('div', { class: 'chart-stage' }, chartCanvas, overlay, chartLegend, typeBar)),
      el(
        'div',
        { class: 'panel trades-panel' },
        el('div', { class: 'panel-head' }, el('h2', {}, 'Your trades'), el('button', { class: 'link small', type: 'button', onClick: () => void refreshTrades() }, 'Refresh')),
        tabs,
        el('div', { class: 'tab-body' }, openList, historyList),
      ),
    ),
    el(
      'aside',
      { class: 'panel trade-panel' },
      el('div', { class: 'panel-head' }, el('h2', {}, 'Place a trade'), badge('SIMULASI', 'sim')),
      el(
        'div',
        { class: 'trade-form' },
        el('label', { class: 'lbl' }, 'Amount'),
        el('div', { class: 'amount-row' }, currencySelect, amountInput),
        quickRow,
        balanceHint,
        el('label', { class: 'lbl' }, 'Duration (seconds)'),
        durationGrid,
        el('div', { class: 'duration-custom-row' }, durationCustom, el('span', { class: 'muted small' }, `sec · ${duration(durationSec)}`)),
        limitsHint,
        previewBtn,
        previewBox,
        el('div', { class: 'trade-actions' }, buyBtn, sellBtn),
        store.user ? null : el('p', { class: 'hint small center' }, el('a', { href: '/login?next=/trading', 'data-link': '' }, 'Sign in'), ' to place a trade.'),
      ),
    ),
  );
  outlet.append(layout);

  // ---------------------------------------------------------------- chart
  chartApi.current = createChart(chartCanvas, { watermark: 'SIMULASI' });
  chartApi.current.onHover = ({ candle, live }) => {
    if (!candle) return;
    chartLegend.replaceChildren(
      legendItem('O', candle.o, dps()),
      legendItem('H', candle.h, dps()),
      legendItem('L', candle.l, dps()),
      legendItem('C', candle.c, dps()),
      legendItem('Live', live, dps(), true),
    );
  };

  function legendItem(label, value, decimals, accent = false) {
    return el('span', { class: accent ? 'legend accent' : 'legend' }, el('b', {}, label), price(value, decimals));
  }

  const tfMs = { '5s': 5000, '15s': 15000, '30s': 30000, '1m': 60000, '5m': 300000, '15m': 900000, '1h': 3600000 };
  function renderTimeframes() {
    tfBar.replaceChildren(
      ...config.timeframes.map((tf) =>
        el('button', { class: `tf-btn ${tf === timeframe ? 'active' : ''}`, type: 'button', onClick: () => setTimeframe(tf) }, tf),
      ),
      el('span', { class: 'grow' }),
      el('span', { class: 'muted small', id: 'liveCountdown' }, '–'),
    );
  }
  function renderTypeBar() {
    typeBar.replaceChildren(
      ...['candle', 'ohlc', 'line', 'area'].map((type) =>
        el('button', {
          class: `type-btn ${chartType === type ? 'active' : ''}`,
          type: 'button',
          title: type,
          onClick: () => {
            chartType = type;
            localStorage.setItem('st.chartType', type);
            chartApi.current.setType(type);
            renderTypeBar();
          },
        }, type),
      ),
      el('button', {
        class: 'type-btn live',
        type: 'button',
        title: 'Jump back to the live edge',
        onClick: () => chartApi.current.goLive(),
      }, 'live'),
    );
  }

  async function setTimeframe(tf) {
    timeframe = tf;
    localStorage.setItem('st.tf', tf);
    renderTimeframes();
    chartApi.current.setTimeframe(tf, tfMs[tf]);
    socket.subscribe(market.symbol, tf);
    await loadCandles();
  }

  async function loadCandles(limit = 300) {
    try {
      const res = await get(`/api/v1/markets/${market.symbol}/candles?tf=${timeframe}&limit=${limit}`);
      serverOffset = res.serverTime - Date.now();
      chartApi.current.setServerOffset(serverOffset);
      chartApi.current.setDecimals(dps());
      chartApi.current.setData(res.candles);
      if (res.current) chartApi.current.applyCandle(res.current);
    } catch (err) {
      toast(`Chart: ${err.message}`, 'lose');
    }
  }

  // -------------------------------------------------------------- markets
  function renderMarkets() {
    marketList.replaceChildren(
      ...store.markets.map((m) =>
        el(
          'button',
          {
            class: `market-item ${m.symbol === market.symbol ? 'active' : ''}`,
            type: 'button',
            onClick: () => selectMarket(m.symbol),
          },
          el('div', { class: 'mi-top' }, el('strong', {}, m.symbol), m.paused ? badge('PAUSED', 'warn') : badge('SIM', 'sim')),
          el('div', { class: 'mi-name muted small' }, m.name),
          el(
            'div',
            { class: 'mi-price' },
            el('span', { class: 'mi-last' }, price(m.ticker?.price, m.priceDecimals)),
            el('span', { class: `mi-chg ${(m.ticker?.change24hPercent ?? 0) >= 0 ? 'up' : 'down'}` }, pct(m.ticker?.change24hPercent)),
          ),
        ),
      ),
    );
  }

  async function selectMarket(symbol) {
    if (symbol === market.symbol) return;
    socket.unsubscribe(market.symbol, timeframe);
    market = store.markets.find((m) => m.symbol === symbol) ?? market;
    setMarket(market.symbol);
    localStorage.setItem('st.market', market.symbol);
    chartApi.current.setDecimals(dps());
    renderMarkets();
    renderTicker();
    renderFormStatic();
    socket.subscribe(market.symbol, timeframe);
    await Promise.all([loadCandles(), refreshTicker(), refreshTrades(), renderMarkers()]);
  }

  function renderTicker() {
    const chg = marketTicker.change24hPercent;
    tickerPanel.replaceChildren(
      el(
        'div',
        { class: 'tk-main' },
        el('div', { class: 'tk-title' }, el('h1', {}, market.symbol), el('span', { class: 'muted small' }, market.name), badge('SIMULASI', 'sim')),
        el(
          'div',
          { class: 'tk-price-row' },
          el('span', { class: `tk-price ${(chg ?? 0) >= 0 ? 'up' : 'down'}`, id: 'livePrice' }, price(marketTicker.price, dps())),
          el('span', { class: `tk-chg ${(chg ?? 0) >= 0 ? 'up' : 'down'}` }, `${pct(chg)} · 24h`),
        ),
        el(
          'div',
          { class: 'tk-meta' },
          el('span', {}, '24h H ', el('b', {}, price(marketTicker.high24h, dps()))),
          el('span', {}, '24h L ', el('b', {}, price(marketTicker.low24h, dps()))),
          el('span', {}, 'Mood ', el('b', {}, market.mood)),
          el('span', {}, 'Trend ', el('b', {}, market.trend)),
          market.paused ? badge('MARKET PAUSED', 'warn') : null,
        ),
      ),
    );
  }

  async function refreshTicker() {
    try {
      const t = await get(`/api/v1/markets/${market.symbol}/ticker`);
      serverOffset = t.serverTime - Date.now();
      marketTicker = t;
      chartApi.current.setServerOffset(serverOffset);
      renderTicker();
    } catch {
      /* ignore */
    }
  }

  // ----------------------------------------------------------- trade form
  function settingsLimits() {
    const cur = currency;
    return {
      min: config.limits.minAmount[cur] ?? 1,
      max: config.limits.maxAmount[cur] ?? 1000,
    };
  }

  function renderQuick() {
    const { min, max } = settingsLimits();
    const step = currency === 'IDR' ? 10_000 : 10;
    quickRow.replaceChildren(
      ...[-step, +step].map((d) =>
        el('button', { class: 'chip', type: 'button', onClick: () => setAmount(amount + d) }, d > 0 ? `+${d}` : `${d}`),
      ),
      el('button', { class: 'chip', type: 'button', onClick: () => setAmount(amount / 2) }, '½'),
      el('button', { class: 'chip', type: 'button', onClick: () => setAmount(amount * 2) }, 'x2'),
      el('button', { class: 'chip', type: 'button', onClick: () => setAmount(min) }, 'min'),
      el('button', { class: 'chip', type: 'button', onClick: () => setAmount(max) }, 'max'),
    );
  }

  function clampAmount(value) {
    const { min, max } = settingsLimits();
    const decimals = currency === 'IDR' ? 0 : 2;
    const rounded = Math.round(value * 10 ** decimals) / 10 ** decimals;
    return Math.max(0, Math.min(max, Number.isFinite(rounded) ? rounded : 0));
  }

  function setAmount(value) {
    amount = clampAmount(value);
    amountInput.value = String(amount);
    localStorage.setItem('st.amount', String(amount));
    renderPreview();
  }

  function renderDurations() {
    const allowed = config.durations.allowed;
    durationGrid.replaceChildren(
      ...PRESETS.filter((p) => allowed.includes(p)).map((p) =>
        el(
          'button',
          {
            class: `dur-btn ${durationSec === p ? 'active' : ''}`,
            type: 'button',
            onClick: () => setDuration(p),
          },
          presetLabel(p),
        ),
      ),
    );
  }

  function setDuration(value) {
    const allowed = config.durations.allowed;
    const v = Math.max(config.durations.minSec, Math.min(config.durations.maxSec, Math.round(value || 0)));
    durationSec = v;
    durationCustom.value = String(v);
    localStorage.setItem('st.duration', String(v));
    renderDurations();
    const hint = durationCustom.parentElement?.querySelector('.muted');
    if (hint) hint.textContent = `sec · ${duration(v)}`;
    renderPreview();
  }

  function formatAmountInput(value) {
    return currency === 'IDR' ? String(Math.round(value)) : String(value);
  }

  function renderFormStatic() {
    const { min, max } = settingsLimits();
    amountInput.step = currency === 'IDR' ? '1000' : '0.01';
    amountInput.min = String(min);
    amountInput.max = String(max);
    amountInput.value = formatAmountInput(amount);
    limitsHint.textContent = `Allowed ${money(min, currency)} – ${money(max, currency)} per trade · payout ${(config.payout.rate * 100).toFixed(0)}% (${config.payout.mode === 'profit' ? 'of stake profit' : 'of stake total'})`;
    renderQuick();
    renderDurations();
    renderPreview();
  }

  function payoutPreview() {
    const rate = config.payout.rate;
    const profit = config.payout.mode === 'profit' ? amount * rate : amount * rate - amount;
    return { payout: amount + profit, profit };
  }

  function renderPreview() {
    const { min, max } = settingsLimits();
    const { payout, profit } = payoutPreview();
    const balance = wallet(currency).balance;
    const issues = [];
    if (amount < min) issues.push(`Minimum ${money(min, currency)}`);
    if (amount > max) issues.push(`Maximum ${money(max, currency)}`);
    if (amount > balance && store.user) issues.push('Insufficient demo balance');
    if (!config.durations.allowed.includes(durationSec)) issues.push('Duration not allowed');
    if (market.paused) issues.push('Market is paused');

    previewBox.replaceChildren(
      el('div', { class: 'preview-row' }, el('span', {}, 'Stake'), el('b', {}, money(amount, currency))),
      el('div', { class: 'preview-row' }, el('span', {}, 'Payout if win'), el('b', { class: 'up' }, money(payout, currency))),
      el('div', { class: 'preview-row' }, el('span', {}, 'Potential profit'), el('b', { class: 'up' }, `+${money(profit, currency)}`)),
      el('div', { class: 'preview-row' }, el('span', {}, 'If lose'), el('b', { class: 'down' }, `-${money(amount, currency)}`)),
      el('div', { class: 'preview-row' }, el('span', {}, 'Tie'), el('b', {}, 'stake refunded')),
      el('div', { class: 'preview-row' }, el('span', {}, 'Expires'), el('b', {}, clock(Date.now() + serverOffset + durationSec * 1000))),
      issues.length ? el('div', { class: 'preview-issues' }, ...issues.map((i) => el('div', { class: 'issue' }, i))) : null,
    );
    const blocked = issues.length > 0 || !store.user;
    buyBtn.classList.toggle('disabled', blocked);
    sellBtn.classList.toggle('disabled', blocked);
    balanceHint.replaceChildren(
      store.user
        ? el('span', {}, 'Balance: ', el('b', {}, money(wallet(currency).balance, currency)))
        : el('span', { class: 'muted' }, 'Sign in to trade'),
      el('span', { class: 'muted small' }, store.user ? `${openTrades.length}/${config.limits.maxOpenTrades} open` : ''),
    );
  }

  amountInput.addEventListener('input', () => {
    amount = clampAmount(Number(amountInput.value));
    localStorage.setItem('st.amount', String(amount));
    renderPreview();
  });
  amountInput.addEventListener('blur', () => setAmount(amount));
  currencySelect.addEventListener('change', () => {
    currency = currencySelect.value;
    amount = clampAmount(amount);
    renderFormStatic();
  });
  durationCustom.addEventListener('change', () => setDuration(Number(durationCustom.value)));
  previewBtn.addEventListener('click', () => {
    const { payout, profit } = payoutPreview();
    void openModal({
      title: 'Payout preview (SIMULASI)',
      confirmLabel: 'Got it',
      cancelLabel: 'Close',
      render: () =>
        el(
          'div',
          { class: 'stack' },
          previewRow('Market', `${market.symbol} · ${market.name}`),
          previewRow('Stake', money(amount, currency)),
          previewRow('Payout rate', `${(config.payout.rate * 100).toFixed(0)}% (${config.payout.mode})`),
          previewRow('Payout if win', money(payout, currency)),
          previewRow('Profit if win', `+${money(profit, currency)}`),
          previewRow('Loss if lose', `-${money(amount, currency)}`),
          previewRow('Duration', `${durationSec}s`),
        ),
    });
  });

  function previewRow(label, value) {
    return el('div', { class: 'kv' }, el('span', { class: 'muted' }, label), el('b', {}, value));
  }

  // --------------------------------------------------------------- placing
  async function place(dir) {
    if (!store.user) {
      navigate('/login?next=/trading');
      return;
    }
    if (!config.durations.allowed.includes(durationSec)) {
      toast('Duration is not allowed by the admin settings', 'lose');
      return;
    }
    const { min, max } = settingsLimits();
    if (amount < min || amount > max) {
      toast(`Amount must be between ${money(min, currency)} and ${money(max, currency)}`, 'lose');
      return;
    }
    const { payout, profit } = payoutPreview();
    const entry = marketTicker.price ?? chartApi.current.getLast();
    const expiry = Date.now() + serverOffset + durationSec * 1000;
    const confirmed = await openModal({
      title: 'Confirm trade',
      confirmLabel: `Confirm ${dir === 'up' ? 'BUY' : 'SELL'}`,
      danger: dir === 'down',
      render: () =>
        el(
          'div',
          { class: 'stack' },
          el('div', { class: 'confirm-grid' },
            previewRow('Market', `${market.symbol}`),
            previewRow('Direction', dir === 'up' ? 'BUY / UP' : 'SELL / DOWN'),
            previewRow('Amount', money(amount, currency)),
            previewRow('Duration', `${durationSec}s`),
            previewRow('Entry price', price(entry, dps())),
            previewRow('Expiry (server time)', new Date(expiry).toLocaleTimeString()),
            previewRow('Payout if win', money(payout, currency)),
            previewRow('Profit if win', `+${money(profit, currency)}`),
          ),
          el('p', { class: 'hint small' }, 'Entry price, expiry and result are decided by the server. Prices are simulated (SIMULASI).'),
        ),
    });
    if (!confirmed) return;

    buyBtn.disabled = sellBtn.disabled = true;
    try {
      const idempotencyKey =
        globalThis.crypto?.randomUUID?.() ?? `key-${Date.now()}-${Math.random().toString(36).slice(2)}`;
      const res = await post(
        '/api/v1/trades',
        { market: market.symbol, direction: dir, currency, amount, durationSec },
        { 'Idempotency-Key': idempotencyKey },
      );
      setWallets(res.wallets ?? []);
      toast(`${dir === 'up' ? 'BUY' : 'SELL'} opened · ${money(amount, currency)}`, 'win');
      await refreshTrades();
      await renderMarkers();
    } catch (err) {
      toast(err.message, 'lose');
    } finally {
      buyBtn.disabled = sellBtn.disabled = false;
      renderPreview();
    }
  }
  buyBtn.addEventListener('click', () => void place('up'));
  sellBtn.addEventListener('click', () => void place('down'));

  // ---------------------------------------------------------------- trades
  function renderTabs() {
    tabs.replaceChildren(
      el('button', { class: `tab ${activeTab === 'open' ? 'active' : ''}`, type: 'button', onClick: () => (activeTab = 'open', renderTabs()) }, `Open (${openTrades.length})`),
      el('button', { class: `tab ${activeTab === 'history' ? 'active' : ''}`, type: 'button', onClick: () => (activeTab = 'history', renderTabs()) }, 'History'),
    );
    openList.hidden = activeTab !== 'open';
    historyList.hidden = activeTab !== 'history';
  }

  async function refreshTrades() {
    if (!store.user) {
      openTrades = [];
      history = [];
      openList.replaceChildren(emptyState('Sign in to see your trades.'));
      historyList.replaceChildren();
      renderTabs();
      renderPreview();
      return;
    }
    try {
      const [open, closed] = await Promise.all([
        get('/api/v1/trades?status=open&limit=50'),
        get('/api/v1/trades?status=closed&limit=50'),
      ]);
      openTrades = open.trades;
      history = closed.trades;
      renderTrades();
      renderMarkers();
    } catch (err) {
      toast(err.message, 'lose');
    }
  }

  function emptyState(text) {
    return el('div', { class: 'empty' }, text);
  }

  function renderTrades() {
    renderTabs();
    openList.replaceChildren(
      ...(openTrades.length
        ? openTrades.map((t) =>
            el(
              'div',
              { class: 'trade-row open' },
              el(
                'div',
                { class: 'tr-main' },
                el('div', { class: 'tr-head' },
                  el('strong', {}, t.market),
                  el('span', { class: `dir ${t.direction}` }, t.direction === 'up' ? 'BUY' : 'SELL'),
                  resultBadge(null),
                ),
                el('div', { class: 'tr-meta muted small' },
                  `entry ${price(t.entryPrice, dps())} · ${money(t.amount, t.currency)} · ${duration(t.durationSec)}`,
                ),
              ),
              el(
                'div',
                { class: 'tr-right' },
                el('div', { class: 'tr-live' }, price(t.livePrice, dps()), el('span', { class: `est ${t.estimatedResult ?? ''}` }, t.estimatedResult ?? 'pending')),
                el('div', { class: 'tr-countdown', dataset: { expires: String(t.expiryTime) } }, '–'),
              ),
            ),
          )
        : [emptyState('No open trades. Place one on the right.')]),
    );
    historyList.replaceChildren(
      ...(history.length
        ? history.map((t) =>
            el(
              'div',
              { class: 'trade-row closed' },
              el('div', { class: 'tr-main' },
                el('div', { class: 'tr-head' },
                  el('strong', {}, t.market),
                  el('span', { class: `dir ${t.direction}` }, t.direction === 'up' ? 'BUY' : 'SELL'),
                  resultBadge(t.result),
                ),
                el('div', { class: 'tr-meta muted small' },
                  `${money(t.amount, t.currency)} · ${duration(t.durationSec)} · ${new Date(t.createdAt).toLocaleTimeString()}`,
                ),
              ),
              el('div', { class: 'tr-right' },
                el('div', { class: 'tr-live' }, t.payout === null ? '–' : money(t.profit, t.currency)),
                el('div', { class: 'muted small' }, `close ${price(t.closePrice, dps())}`),
              ),
            ),
          )
        : [emptyState('No settled trades yet.')]),
    );
  }

  /** Entry/expiry markers for the chart (server prices only). */
  async function renderMarkers() {
    const markers = [];
    for (const t of openTrades.filter((x) => x.market === market.symbol)) {
      markers.push({ kind: 'entry', price: t.entryPrice, direction: t.direction, open: true, expiryTime: t.expiryTime });
    }
    for (const t of history.slice(0, 8).filter((x) => x.market === market.symbol)) {
      markers.push({ kind: 'entry', price: t.entryPrice, direction: t.direction, open: false, expiryTime: t.expiryTime });
      if (t.closePrice) markers.push({ kind: 'expiry', price: t.closePrice, direction: t.direction, open: false, expiryTime: t.expiryTime });
    }
    chartApi.current.setMarkers(markers);
  }

  function tickCountdowns() {
    const now = Date.now() + serverOffset;
    for (const node of document.querySelectorAll('.tr-countdown')) {
      const expires = Number(node.dataset.expires);
      const left = Math.max(0, expires - now);
      node.textContent = left > 0 ? `${(left / 1000).toFixed(1)}s left` : 'settling…';
      node.classList.toggle('urgent', left < 10_000);
    }
    const tfNode = document.getElementById('liveCountdown');
    if (tfNode) {
      const ms = tfMs[timeframe] ?? 60_000;
      const left = ms - (now % ms);
      tfNode.textContent = `${timeframe} closes in ${(left / 1000).toFixed(1)}s`;
    }
    // refresh live estimates for open trades every second, using the tick we already have
    if (openTrades.length) {
      openList.querySelectorAll('.trade-row.open').forEach((row, i) => {
        const t = openTrades[i];
        if (!t) return;
        const live = marketTicker.price;
        if (!live) return;
        const est = live > t.entryPrice ? (t.direction === 'up' ? 'win' : 'lose') : live < t.entryPrice ? (t.direction === 'up' ? 'lose' : 'win') : 'draw';
        const liveNode = row.querySelector('.tr-live');
        if (liveNode) {
          liveNode.firstChild.textContent = price(live, dps());
          const estNode = liveNode.querySelector('.est');
          if (estNode) {
            estNode.textContent = est;
            estNode.className = `est ${est}`;
          }
        }
      });
    }
  }

  // ------------------------------------------------------------ socket feed
  const off = onSocketMessage((msg) => {
    if (msg.type === 'tick' && msg.market === market.symbol) {
      marketTicker.price = msg.price;
      chartApi.current.push(msg.price, msg.time);
      const node = document.getElementById('livePrice');
      if (node) {
        node.textContent = price(msg.price, dps());
        node.className = `tk-price ${msg.price >= (marketTicker.change24h != null && marketTicker.price != null ? marketTicker.price - marketTicker.change24h : msg.price) ? 'up' : 'down'}`;
      }
    } else if (msg.type === 'candle' && msg.market === market.symbol && msg.tf === timeframe) {
      chartApi.current.applyCandle({ t: msg.t, o: msg.o, h: msg.h, l: msg.l, c: msg.c });
    } else if (msg.type === 'candle_closed' && msg.market === market.symbol && msg.tf === timeframe) {
      chartApi.current.closeCandle(msg.candle);
    } else if (msg.type === 'trade:opened' || msg.type === 'trade:settled') {
      if (msg.type === 'trade:settled') {
        const cur = msg.trade?.currency ?? 'USD';
        toast(`Trade settled: ${msg.result.toUpperCase()} · ${money(msg.payout, cur)}`, msg.result === 'lose' ? 'lose' : 'win');
      }
      void refreshTrades();
    } else if (msg.type === 'replay' && msg.market === market.symbol) {
      for (const t of msg.ticks) chartApi.current.push(t.price, t.time);
      for (const c of msg.candles) if (c.tf === timeframe) chartApi.current.applyCandle(c);
    } else if (msg.type === 'resync') {
      void loadCandles();
    } else if (msg.type === 'error') {
      console.warn('ws error', msg);
    }
  });

  const unsubscribeStore = subscribe(() => {
    if (!store.user) return;
    renderMarkets();
    renderPreview();
  });

  // ------------------------------------------------------------- lifecycle
  renderMarkets();
  renderTicker();
  renderTimeframes();
  renderTypeBar();
  renderFormStatic();
  chartApi.current.setTimeframe(timeframe, tfMs[timeframe]);
  chartApi.current.setType(chartType);
  chartApi.current.setDecimals(dps());
  socket.subscribe(market.symbol, timeframe);
  await Promise.all([loadCandles(), refreshTicker(), refreshTrades()]);
  renderPreview();

  const counters = setInterval(() => {
    tickCountdowns();
    renderPreview();
  }, 1000);
  const tickerTimer = setInterval(() => void refreshTicker(), 15_000);
  const tradesTimer = setInterval(() => void refreshTrades(), 5_000);

  const cleanup = () => {
    clearInterval(counters);
    clearInterval(tickerTimer);
    clearInterval(tradesTimer);
    off();
    unsubscribeStore();
    socket.unsubscribe(market.symbol, timeframe);
    window.removeEventListener('beforeunload', cleanup);
  };
  window.addEventListener('beforeunload', cleanup);
  const observer = new MutationObserver(() => {
    if (!document.body.contains(layout)) {
      cleanup();
      observer.disconnect();
    }
  });
  observer.observe(document.getElementById('view'), { childList: true });
}
