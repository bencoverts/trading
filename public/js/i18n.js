const dictionaries = { id, en };
let current = 'id';

export function setLanguage(lang) {
  current = lang === 'en' ? 'en' : 'id';
  document.documentElement.lang = current;
  return current;
}

export function getLanguage() {
  return current;
}

export function t(key, vars = {}) {
  const dict = dictionaries[current] ?? id;
  const template = dict[key] ?? id[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_match, name) =>
    vars[name] !== undefined ? String(vars[name]) : `{${name}}`,
  );
}

/** Applies translations to every element with data-i18n. */
export function translateDom(root = document) {
  for (const node of root.querySelectorAll('[data-i18n]')) {
    const key = node.getAttribute('data-i18n');
    if (!key) continue;
    const value = t(key);
    if (!value) continue;
    if (node.hasAttribute('data-i18n-attr')) node.setAttribute(node.getAttribute('data-i18n-attr'), value);
    else node.textContent = value;
  }
}
