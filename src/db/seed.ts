export interface SeedResult {
  marketsInserted: number;
  adminCreated: boolean;
  settingsCreated: boolean;
  demoUsers: number;
  demoStaff: number;
  demoTrades: number;
}

export interface SeedOptions {
  /** creates demo users and sample trades (on by default outside production) */
  demoData?: boolean;
}

/**
 * Idempotent seed: three markets, default runtime settings, the initial
 * super-admin, and (for demos) a few users with sample trades.
 */
export async function seedDatabase(
  db: Database,
  config: Config,
  hasher: PasswordHasher,
  settings?: SettingsService,
  options: SeedOptions = {},
): Promise<SeedResult> {
  const now = Date.now();
  const result: SeedResult = {
    marketsInserted: 0,
    adminCreated: false,
    settingsCreated: false,
    demoUsers: 0,
    demoStaff: 0,
    demoTrades: 0,
  };
  const ledger = new LedgerService(db);

  db.transaction(() => {
    for (const market of SEED_MARKETS) {
      if (db.get('SELECT symbol FROM markets WHERE symbol = ?', market.symbol)) continue;
      db.run(
        `INSERT INTO markets (symbol, name, description, category, price_decimals, base_price, tick_size, tick_interval_ms,
                              mood, trend, trend_strength, volatility, volatility_preset, trading_hours,
                              min_amount_usd_minor, max_amount_usd_minor, payout_rate, exposure_limit_usd_minor,
                              featured, is_draft, paused, active, sort_order, created_at, updated_at)
         VALUES (?, ?, ?, ?, ?, ?, ?, 100, ?, ?, 5, ?, ?, ?, ?, ?, ?, ?, ?, 0, 0, 1, ?, ?, ?)`,
        market.symbol,
        market.name,
        market.description,
        market.category,
        market.priceDecimals,
        market.basePrice,
        market.tickSize,
        market.mood,
        market.trend,
        VOLATILITY_PRESETS[market.volatilityPreset].multiplier,
        market.volatilityPreset,
        JSON.stringify({ mode: '24_7' }),
        Math.round(market.minAmountUsd * 100),
        Math.round(market.maxAmountUsd * 100),
        market.payoutRate,
        Math.round(market.exposureLimitUsd * 100),
        market.featured ? 1 : 0,
        market.sortOrder,
        now,
        now,
      );
      result.marketsInserted += 1;
    }

    const settingsRow = db.get<{ key: string }>('SELECT key FROM settings WHERE key = ?', 'runtime');
    if (!settingsRow) {
      db.run(
        'INSERT INTO settings (key, value, updated_at) VALUES (?, ?, ?)',
        'runtime',
        JSON.stringify(DEFAULT_SETTINGS),
        now,
      );
      result.settingsCreated = true;
    }
  });

  const ensureUser = async (input: {
    email: string;
    username: string;
    password: string;
    displayName: string;
    staffRole: 'super_admin' | 'operator' | 'support' | 'viewer' | null;
    verified: boolean;
  }): Promise<string | null> => {
    const email = input.email.trim().toLowerCase();
    const existing = db.get<{ id: string }>(
      'SELECT id FROM users WHERE email_normalized = ? OR username_normalized = ?',
      email,
      input.username.trim().toLowerCase(),
    );
    if (existing) return null;
    const passwordHash = await hasher.hash(input.password);
    const id = newId();
    const balances = (settings ?? { get: () => DEFAULT_SETTINGS }).get().initialBalance;
    db.transaction(() => {
      db.run(
        `INSERT INTO users (id, email, email_normalized, username, username_normalized, password_hash, role, staff_role,
                            display_name, email_verified_at, display_currency, token_version, created_at, updated_at,
                            terms_accepted_at, language, timezone, last_seen_at)
         VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 'USD', 0, ?, ?, ?, 'id', 'Asia/Jakarta', ?)`,
        id,
        input.email,
        email,
        input.username,
        input.username.toLowerCase(),
        passwordHash,
        input.staffRole ? 'admin' : 'user',
        input.staffRole,
        input.displayName,
        input.verified ? now : null,
        now,
        now,
        now,
        now,
      );
      for (const currency of CURRENCY_LIST) {
        db.run(
          'INSERT INTO wallets (user_id, currency, balance_minor, updated_at) VALUES (?, ?, ?, ?)',
          id,
          currency,
          balances[currency],
          now,
        );
        ledger.write({
          userId: id,
          currency,
          kind: 'seed_initial_balance',
          direction: 'credit',
          amountMinor: Math.max(1, balances[currency]),
          balanceAfterMinor: balances[currency],
          note: 'saldo awal demo (seed)',
          now,
        });
      }
      recordAudit(db, {
        actorUserId: id,
        actorRole: 'system',
        action: input.staffRole ? 'admin.seeded' : 'user.seeded',
        targetType: 'user',
        targetId: id,
        meta: { email: input.email, username: input.username, staffRole: input.staffRole },
        now,
      });
    });
    return id;
  };

  const adminId = await ensureUser({
    email: config.ADMIN_EMAIL,
    username: config.ADMIN_USERNAME,
    password: config.ADMIN_PASSWORD,
    displayName: 'Super Admin',
    staffRole: 'super_admin',
    verified: true,
  });
  if (adminId) result.adminCreated = true;

  if (options.demoData !== false) {
    for (const demo of DEMO_USERS) {
      const id = await ensureUser({
        email: demo.email,
        username: demo.username,
        password: demo.password,
        displayName: demo.displayName,
        staffRole: null,
        verified: demo.verified,
      });
      if (id) result.demoUsers += 1;
    }
    const supportId = await ensureUser({
      email: 'support@simtrade.local',
      username: 'support',
      password: 'support-password-123',
      displayName: 'Support Staff',
      staffRole: 'support',
      verified: true,
    });
    if (supportId) result.demoStaff += 1;
    const operatorId = await ensureUser({
      email: 'operator@simtrade.local',
      username: 'operator',
      password: 'operator-password-123',
      displayName: 'Market Operator',
      staffRole: 'operator',
      verified: true,
    });
    if (operatorId) result.demoStaff += 1;

    result.demoTrades = seedDemoTrades(db, now, ledger);
  }

  return result;
}

/**
 * A handful of settled + open sample trades so every list and the dashboard
 * have content on a fresh install. Entries are marked with their own
 * idempotency keys, so re-running the seed does not duplicate them.
 */
function seedDemoTrades(db: Database, now: number, ledger: LedgerService): number {
  const traders = db.all<{ id: string; email: string }>(
    `SELECT id, email FROM users WHERE staff_role IS NULL AND email IN (?, ?, ?)`,
    DEMO_USERS[0].email,
    DEMO_USERS[1].email,
    DEMO_USERS[2].email,
  );
  if (!traders.length) return 0;

  const markets = db.all<{ symbol: string; base_price: number; price_decimals: number; payout_rate: number | null }>(
    'SELECT symbol, base_price, price_decimals, payout_rate FROM markets WHERE deleted_at IS NULL LIMIT 3',
  );
  if (!markets.length) return 0;

  const plan: Array<{
    market: string;
    direction: 'up' | 'down';
    amountMinor: number;
    durationSec: number;
    result: 'win' | 'lose' | 'draw';
  }> = [
    { market: markets[0].symbol, direction: 'up', amountMinor: 2_500, durationSec: 60, result: 'win' },
    { market: markets[0].symbol, direction: 'down', amountMinor: 1_000, durationSec: 300, result: 'lose' },
    {
      market: markets[1 % markets.length].symbol,
      direction: 'up',
      amountMinor: 5_000,
      durationSec: 60,
      result: 'draw',
    },
    {
      market: markets[1 % markets.length].symbol,
      direction: 'down',
      amountMinor: 2_000,
      durationSec: 900,
      result: 'win',
    },
    {
      market: markets[2 % markets.length].symbol,
      direction: 'up',
      amountMinor: 1_500,
      durationSec: 30,
      result: 'lose',
    },
  ];

  let created = 0;
  for (const [index, item] of plan.entries()) {
    const key = `seed-demo-${index}`;
    if (db.get('SELECT id FROM trades WHERE idempotency_key = ?', key)) continue;
    const market = markets.find((m) => m.symbol === item.market) ?? markets[0];
    const trader = traders[index % traders.length];
    const id = newId();
    const entryTime = now - (index + 2) * 3_600_000;
    const expiryTime = entryTime + item.durationSec * 1000;
    const f = 10 ** market.price_decimals;
    const entryPrice = market.base_price;
    const move = item.result === 'draw' ? 0 : item.result === 'win' ? 1 : -1;
    const drift = (item.direction === 'up' ? 1 : -1) * move;
    const closePrice = Math.round(entryPrice * (1 + drift * 0.0015) * f) / f;
    const payoutRate = market.payout_rate ?? 0.85;
    const payoutMinor =
      item.result === 'lose'
        ? 0
        : item.result === 'draw'
          ? item.amountMinor
          : item.amountMinor + Math.round(item.amountMinor * payoutRate);
    const settledAt = expiryTime + 250;

    db.transaction(() => {
      const balance = Number(
        db.get<{ balance_minor: number }>(
          'SELECT balance_minor FROM wallets WHERE user_id = ? AND currency = ?',
          trader.id,
          'USD',
        )?.balance_minor ?? 0,
      );
      db.run(
        `INSERT INTO trades (id, user_id, market, direction, currency, amount_minor, duration_sec, entry_price, entry_time,
                             expiry_time, close_price, settled_at, status, result, payout_rate, payout_mode, payout_minor,
                             settled_by, idempotency_key, request_hash, created_at)
         VALUES (?, ?, ?, ?, 'USD', ?, ?, ?, ?, ?, ?, ?, 'closed', ?, ?, 'profit', ?, 'expiry', ?, 'seed', ?)`,
        id,
        trader.id,
        market.symbol,
        item.direction,
        item.amountMinor,
        item.durationSec,
        entryPrice,
        entryTime,
        expiryTime,
        closePrice,
        settledAt,
        item.result,
        payoutRate,
        payoutMinor,
        key,
        entryTime,
      );
      // demo trades are already reflected in the seeded starting balance, so the
      // ledger is written with the closing balance rather than moving money now
      ledger.write({
        userId: trader.id,
        currency: 'USD',
        kind: 'trade_stake',
        direction: 'debit',
        amountMinor: item.amountMinor,
        balanceAfterMinor: balance,
        refType: 'trade',
        refId: id,
        meta: { seed: true },
        now: entryTime,
      });
      if (payoutMinor > 0) {
        ledger.write({
          userId: trader.id,
          currency: 'USD',
          kind: item.result === 'draw' ? 'trade_refund' : 'trade_payout',
          direction: 'credit',
          amountMinor: payoutMinor,
          balanceAfterMinor: balance,
          refType: 'trade',
          refId: id,
          meta: { seed: true },
          now: settledAt,
        });
      }
    });
    created += 1;
  }
  return created;
}
